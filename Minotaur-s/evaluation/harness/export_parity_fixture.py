"""Exports scored passages from a harness run as a Swift test fixture, so `EvidenceScorer.swift`
is checked against `evidence.py` on real dev passages.

Usage: `.venv/bin/python export_parity_fixture.py RUN [N]` → `Minotaur-sTests/Verificador/EvidenceParityFixtures.swift`.
"""
import json
import random
import sys
from pathlib import Path

import evidence
from run_dev import ARTIFACTS

run = sys.argv[1]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 80
OUT = Path(__file__).resolve().parents[2] / "Minotaur-sTests/Verificador/EvidenceParityFixtures.swift"


def swift(s: str) -> str:
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ord(ch) < 32 or 0x7f <= ord(ch) < 0xa0 or 0x200b <= ord(ch) <= 0x200f:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def swift_list(items: list[str]) -> str:
    return "[" + ", ".join(swift(x) for x in items) + "]"


voting, silent = [], []
for path in sorted((ARTIFACTS / run).glob("*.json")):
    res = json.loads(path.read_text())
    feats = evidence.claim_features(res["claim"])
    for src in res["sources"]:
        for ps in src["passages"]:
            sc = evidence.score_passage(res["claim"], ps, evidence.DEFAULT_POLICY, feats)
            row = (res["claim"], feats["anchors"], ps, sc)
            (voting if sc["support"] or sc["refute"] else silent).append(row)

rng = random.Random(7)
rows = rng.sample(voting, min(len(voting), n * 3 // 4)) + rng.sample(silent, min(len(silent), n // 4))
lines = ["// Generated by evaluation/harness/export_parity_fixture.py from the dev (not gold) set. Do not edit.",
         "@testable import Minotaur_s", "", "enum EvidenceParityFixtures {",
         "    struct Case { let claim: String; let anchors: [String]; let text: String; let e, n, c, similarity, support, refute: Double }",
         "    static let cases: [Case] = ["]
for claim, anchors, ps, sc in rows:
    pr = ps["probs"]
    lines.append(f"        Case(claim: {swift(claim)}, anchors: {swift_list(anchors)}, text: {swift(ps['text'])}, "
                 f"e: {pr['entailment']!r}, n: {pr['neutral']!r}, c: {pr['contradiction']!r}, similarity: {ps['similarity']!r}, "
                 f"support: {sc['support']!r}, refute: {sc['refute']!r}),")
lines += ["    ]", "}", ""]
OUT.write_text("\n".join(lines))
print(f"{len(rows)} cases ({sum(1 for r in rows if r[3]['support'] or r[3]['refute'])} voting) -> {OUT}")
